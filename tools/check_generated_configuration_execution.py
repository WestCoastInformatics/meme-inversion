#!/usr/bin/env python3
"""Common generated-settings locks, package transport and audit-boundary checks."""
import base64
import copy
import json
from unittest.mock import patch

import inversion_request as request
import inversion_worker as worker
import mth_configuration
import snomed_configuration


def check():
    passed = []

    def good(value, label):
        if not value:
            raise AssertionError(label)
        passed.append(label)

    def reject(action, label):
        try:
            action()
        except (ValueError, KeyError, TypeError, RuntimeError):
            passed.append(label)
        else:
            raise AssertionError(label)

    original = request.blob
    head = request.commit('HEAD')

    def fixture_blob(ref, name):
        path = request.ROOT / name
        if ref == head and (name.startswith(('tools/', 'docs/')) or name == 'baseline/manifest.json'):
            return path.read_bytes()
        return original(ref, name)

    locks = {}
    for source, filename, profile, count in [
        ('SNOMEDCT_US', 'snomed-generated-configuration.json', 'snomed-properties-v1', 1),
        ('MTH', 'mth-generated-configuration.json', 'mth-prepared-spec-v1', 7),
    ]:
        value = request.load(request.DOCS / 'request-examples' / filename)
        with patch.object(request, 'blob', side_effect=fixture_blob):
            lock = request.resolve(value, source.lower().replace('_', '-') + '-generated-fixture')
        lock = json.loads(json.dumps(lock))
        worker.verify_lock(lock)
        passed.append('Resolved saved generated-settings lock verifies: ' + source)
        recipe = lock['configuration_generation']
        good(recipe['profile'] == profile and len(recipe['files']) == count, 'Correct source profile and generated file inventory: ' + source)
        good(all(item['mode'] == '0o444' for item in recipe['files']), 'All generated settings are read-only: ' + source)
        good(all(name in lock['modules_b64'] for name in ('mth_configuration.py', 'snomed_configuration.py')), 'Both source generators are frozen in the executable apparatus: ' + source)
        before = request.digest(lock)
        package = worker.package(lock)
        good(package['generated_configuration'] == recipe and package['configuration_generation_inputs'] == {
             'configuration': lock['configuration'], 'artifacts': lock['case']['artifacts']}, 'Execution package binds recipe to common configuration and artifacts: ' + source)
        if source == 'SNOMEDCT_US':
            good(snomed_configuration.validate_execution_recipe(recipe, package['configuration_generation_inputs'],
                 contract=package['contract'], code_files=package['code_files']) == recipe,
                 'Actual SNOMED execution contract recomputes the common generated recipe')
            import prepare_snomed_candidate
            with patch.object(prepare_snomed_candidate, 'prepare', return_value={'fixture': True}) as prepared:
                worker.prepare(lock, None)
                good(prepared.call_args.kwargs['generated_configuration'] == recipe and
                     prepared.call_args.kwargs['configuration_generation_inputs'] == package['configuration_generation_inputs'],
                     'Common worker passes both generated settings inputs into SNOMED staging')
        else:
            import replay_mth_core
            good(replay_mth_core.generated_recipe(package) == recipe,
                 'Actual MTH execution package recomputes the common generated recipe')
            good(worker.correction_profile(lock) and lock['request']['comparison_profile'] == 'reviewed-corrections',
                 'Generated MTH still requires its native-derived correction audit')
        package['configuration_generation_inputs']['configuration']['source_atom_ids']['end'] += 1
        good(request.digest(lock) == before, 'Package mutation cannot change the original locked configuration: ' + source)
        for label, mutate in [
            ('missing recipe', lambda x: x.pop('configuration_generation')),
            ('changed generated bytes', lambda x: x['configuration_generation']['files'][0].update(data_b64='Y2hhbmdlZA==')),
            ('missing generation profile', lambda x: x['case'].pop('configuration_generation')),
            ('wrong generation profile', lambda x: x['case']['configuration_generation'].update(profile='nci-properties-v1')),
            ('hidden execution variant', lambda x: (x['request'].update(case_variant='as-produced'), x['configuration']['replay'].update(case_variant='as-produced'), x['case']['configuration']['replay'].update(case_variant='as-produced'), x['case'].update(case_variant='as-produced'))),
        ]:
            bad = copy.deepcopy(lock)
            mutate(bad)
            bad['case_sha256'] = request.digest(bad['case'])
            bad['lock_sha256'] = request.digest({key: item for key, item in bad.items() if key != 'lock_sha256'})
            reject(lambda: worker.verify_lock(bad), 'Rehashed lock rejects ' + label + ': ' + source)
        locks[source] = lock
    mth = copy.deepcopy(locks['MTH'])
    mth['case'].pop('correction_audit')
    mth['case_sha256'] = request.digest(mth['case'])
    mth['lock_sha256'] = request.digest({key: item for key, item in mth.items() if key != 'lock_sha256'})
    reject(lambda: worker.verify_lock(mth), 'Generated MTH cannot drop its required correction audit')
    module_bytes = {name: base64.b64decode(data, validate=True) for name, data in locks['MTH']['modules_b64'].items()}
    request.validate_module_dependencies(module_bytes)
    passed.append('Generated apparatus contains all repository Python dependencies')
    reject(lambda: request.validate_module_dependencies({name: raw for name, raw in module_bytes.items() if name != 'mth_configuration.py'}), 'Missing MTH generator rejected by frozen import closure')
    reject(lambda: request.validate_module_dependencies({name: raw for name, raw in module_bytes.items() if name != 'snomed_configuration.py'}), 'Missing SNOMED generator rejected by frozen import closure')
    return passed


if __name__ == '__main__':
    values = check()
    for value in values:
        print('PASS', value)
    print(len(values), 'common generated-configuration execution checks passed')
