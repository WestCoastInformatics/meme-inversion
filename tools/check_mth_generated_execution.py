#!/usr/bin/env python3
"""Exercise generated MTH staging, mutation gates and frozen Perl consumption."""
import base64
import copy
import json
from pathlib import Path
import subprocess
import tempfile
from unittest.mock import patch

import check_mth_configuration
import mth_configuration as mth
import replay_mth_core as replay

ROOT = Path(__file__).resolve().parents[1]


def fixture(variant='consistent-retained-identities'):
    lock = check_mth_configuration.frozen_fixture(variant)
    case, config = lock['case'], lock['configuration']
    case['configuration_generation'] = {'profile': mth.EXECUTION_PROFILE}
    case['case_variant'] = 'generated-configuration'
    case['configuration']['replay']['case_variant'] = 'generated-configuration'
    config['replay']['case_variant'] = 'generated-configuration'
    lock['case_sha256'] = mth.digest(case)
    lock['configuration_generation'] = mth.execution_recipe(config, case, lock['code_files'])
    package = copy.deepcopy(case['legacy_case'])
    package['code_files'] = copy.deepcopy(lock['code_files'])
    # A real executable is staged independently of generated configuration.
    for item in case['source_files']:
        if item['relative_path'] == 'autoinv.pl':
            path = 'sources/MTH_2026AA/autoinv.pl'
            raw = subprocess.check_output(['git', '-C', str(ROOT), 'show', config['engine_ref'] + ':' + path])
            package['code_files'].append({**item, 'repository_path': path,
                'data_b64': base64.b64encode(raw).decode(), 'bytes': len(raw)})
    package['generated_configuration'] = copy.deepcopy(lock['configuration_generation'])
    package['configuration_generation_inputs'] = {
        'configuration': copy.deepcopy(config), 'artifacts': copy.deepcopy(case['artifacts'])}
    return lock, package


def check():
    passed = []

    def good(value, label):
        assert value, label
        passed.append(label)

    def reject(action, label):
        try:
            action()
        except (RuntimeError, ValueError, KeyError, TypeError, FileExistsError):
            passed.append(label)
        else:
            raise AssertionError(label)

    lock, package = fixture()
    recipe = mth.execution_recipe_from_lock(lock)
    good(recipe['profile'] == mth.EXECUTION_PROFILE and recipe['profile'] != mth.PROFILE,
         'Generated execution has a distinct profile from offline preview')
    good('native_inversion_executed' not in recipe['coverage'] and
         recipe['coverage']['native_conversion'] == 'separate worker execution; outcome recorded in run result',
         'Execution recipe leaves actual native outcome to the separately identified worker result')
    good(recipe == replay.generated_recipe(package),
         'Resolver construction, finalized lock and execution package recompute the same recipe')
    good(mth.execution_recipe_from_lock(json.loads(json.dumps(lock))) == recipe,
         'Finalized execution recipe survives a saved-JSON round trip')
    oldlock, oldpackage = fixture('as-produced')
    good(mth.execution_recipe_from_lock(oldlock)['bindings']['engine_ref'] != recipe['bindings']['engine_ref'] and
         replay.generated_recipe(oldpackage)['files'][1]['sha256'] != recipe['files'][1]['sha256'],
         'Original and corrected engines keep different specs and outputs behind the same generation API')
    original = copy.deepcopy(package)
    receipt = mth.receipt(recipe)
    good(receipt['recipe_sha256'] == mth.digest(recipe) and
         all('data_b64' not in item for item in receipt['files']),
         'Generation receipt binds the complete recipe without inline file payloads')
    for label, mutate in [
        ('changed generated bytes', lambda l: l['configuration_generation']['files'][0].update(data_b64='Y2hhbmdlZA==')),
        ('changed output mode', lambda l: l['configuration_generation']['files'][0].update(mode='0o644')),
        ('unsafe output path', lambda l: l['configuration_generation']['files'][0].update(relative_path='../range3.spec')),
        ('missing generated file', lambda l: l['configuration_generation']['files'].pop()),
        ('preview substituted for execution', lambda l: l['configuration_generation'].update(profile=mth.PROFILE)),
        ('unreviewed execution profile', lambda l: l['case']['configuration_generation'].update(profile='unknown')),
        ('changed frozen case', lambda l: l['case']['known_limits'].append('waiver')),
    ]:
        bad = copy.deepcopy(lock)
        mutate(bad)
        reject(lambda: mth.execution_recipe_from_lock(bad), 'Reject locked ' + label)
    for label, mutate in [
        ('missing generation inputs', lambda p: p.pop('configuration_generation_inputs')),
        ('missing generated recipe', lambda p: p.pop('generated_configuration')),
        ('extra generation override', lambda p: p['configuration_generation_inputs'].update(overrides={})),
        ('selected engine mismatch', lambda p: p.update(engine_ref='0' * 40)),
        ('mutated recipe hash', lambda p: p['generated_configuration']['files'][0].update(sha256='0' * 64)),
        ('mutated source oracle bytes', lambda p: p['code_files'][0].update(data_b64='Y2hhbmdlZA==')),
        ('missing source oracle', lambda p: p.update(code_files=p['code_files'][1:])),
        ('duplicate source oracle', lambda p: p['code_files'].append(copy.deepcopy(p['code_files'][0]))),
        ('actual metadata mismatch', lambda p: p['metadata_inputs'][0].update(sha256='0' * 64)),
        ('actual native-input mismatch', lambda p: p['prepared_subset']['files'][0]['identity'].update(sha256='0' * 64)),
        ('actual identity-map mismatch', lambda p: p['prior_map'].update(sha256='0' * 64)),
        ('actual prior-archive mismatch', lambda p: p.update(prior_archive_sha256='0' * 64)),
    ]:
        bad = copy.deepcopy(package)
        mutate(bad)
        with tempfile.TemporaryDirectory(prefix='mth-rejected-stage-') as temporary:
            target = Path(temporary)
            reject(lambda: replay.stage_code_files(bad, target), 'Reject package ' + label + ' before staging')
            good(not list(target.iterdir()), 'Rejected ' + label + ' writes no candidate file')
    # Exercise the real staging function without any server/environment mocks.
    with tempfile.TemporaryDirectory(prefix='mth-generated-stage-') as temporary:
        target = Path(temporary)
        staged = replay.stage_code_files(package, target)
        good(staged == receipt and package == original,
             'Staging returns the bound receipt and preserves all input descriptors')
        good((target / 'old').is_symlink() and (target / 'old').readlink().as_posix() == '../MTH_2025AB' and
             (target / 'prev').is_symlink() and (target / 'prev').readlink().as_posix() == '../MTH_2025AB',
             'Staging retains distinct captured old/prev topology')
        good((target / 'autoinv.pl').stat().st_mode & 0o777 == 0o750,
             'Independent Git executable retains its captured executable mode')
        for item in recipe['files']:
            path = target / item['relative_path']
            good(path.read_bytes() == base64.b64decode(item['data_b64']) and path.stat().st_mode & 0o777 == 0o444,
                 'Actual staging generates read-only recipe file: ' + item['relative_path'])
        good(replay.verify_generated(package, target) == receipt,
             'Pre-conversion generated-file hashes and exact modes verify')
        settings = target / 'range3.spec'
        settings.chmod(0o644)
        reject(lambda: replay.verify_generated(package, target), 'Writable generated settings fail verification')
        settings.chmod(0o400)
        reject(lambda: replay.verify_generated(package, target), 'Changed read-only mode also fails verification')
        settings.chmod(0o444)
        raw = settings.read_bytes()
        settings.chmod(0o644)
        settings.write_bytes(raw + b'# changed\n')
        settings.chmod(0o444)
        reject(lambda: replay.verify_generated(package, target), 'Changed generated content fails post-conversion verification')
        settings.chmod(0o644)
        settings.write_bytes(raw)
        settings.chmod(0o444)
        settings.unlink()
        outside = target / 'other-range.spec'
        outside.write_bytes(raw)
        outside.chmod(0o444)
        settings.symlink_to(outside)
        reject(lambda: replay.verify_generated(package, target), 'Generated settings replaced by an identical symlink are rejected')
        settings.unlink()
        settings.write_bytes(raw)
        settings.chmod(0o444)
        # Read generated files and put only the isolated fixture's SourceDir into
        # a separate spec; preserve all staged files for the final verification.
        src = target / 'fixture'
        src.mkdir()
        spec = (target / 'src/inv1.spec').read_text().replace(
            '/local/content/MEME/MEME5/inv/sources/MTH_2026AA/src', str(src))
        (src / 'inv1.spec').write_text(spec)
        for name, value in [('class_src', ''), ('sabs_updated_umls', 'TEST\n'),
                            ('vcodes_updated', ''), ('auis_nonupdatedSAB_moved', '')]:
            (src / name).write_text(value)
        (src / 'MRCONSO.RRF').write_text('C1|ENG|P|L1|PF|S1|Y|A1||||TEST|PT|T1|Alpha|0|N||\n')
        run = subprocess.run(['/usr/bin/perl', str(target / 'autoinv.pl'), str(settings), 'inv1.spec'],
                             cwd=src, capture_output=True, text=True, timeout=30)
        good(run.returncode == 0 and (src / 'classes_atoms.src').read_text() ==
             '769443594|TEST|TEST/PT|T1|R|Y|A|Alpha|N||||ENG|needs_order_id|N|C1|A1\n' and
             (src / 'aui_said_map').read_text() == 'A1|C1|N|769443594\n',
             'Actually staged Git Perl consumes generated range/spec with golden atom and identity-map output')
        good(replay.verify_generated(package, target) == receipt,
             'Post-fixture conversion verification proves all seven staged settings unchanged')
    legacy = copy.deepcopy(package)
    legacy.pop('generated_configuration')
    legacy.pop('configuration_generation_inputs')
    with tempfile.TemporaryDirectory(prefix='mth-legacy-stage-') as temporary:
        target = Path(temporary)
        good(replay.stage_code_files(legacy, target) is None and replay.generated_recipe(legacy) is None,
             'Existing nongenerated historical package retains the original staging route')
        good((target / 'range3.spec').stat().st_mode & 0o777 == 0o640,
             'Historical source-descriptor modes are unchanged when generation is not selected')
    with patch.object(replay, 'verify_generated', side_effect=RuntimeError('generated gate')):
        reject(lambda: replay.verify_inputs(package, Path('/unused')),
               'Every full input verification invokes the generated-file gate first')
    return passed


if __name__ == '__main__':
    values = check()
    for value in values:
        print('PASS', value)
    print(len(values), 'MTH generated-execution checks passed')
